import '../../../core/money.dart';

enum EntryKind { income, expense }

class BudgetCategory {
  const BudgetCategory({
    required this.id,
    required this.name,
    required this.kind,
    this.description = '',
  });
  final String id;
  final String name;
  final EntryKind kind;
  final String description;
}

class BudgetEntry {
  const BudgetEntry({
    required this.id,
    required this.categoryId,
    required this.year,
    required this.month,
    required this.amountCents,
    this.description = '',
  });
  final String id;
  final String categoryId;
  final int year;
  final int month;
  final int amountCents;
  final String description;
}

class BudgetSummary {
  const BudgetSummary(this.income, this.expense);
  final int income;
  final int expense;
  int get balance => income - expense;
}

/// One aggregate per sheet; no global lists shared across families or years.
/// Server authorization must still check sheet ownership and active membership.
class BudgetLedger {
  BudgetLedger({
    required this.id,
    required this.familyId,
    required this.ownerId,
  });
  final String id;
  final String familyId;
  final String ownerId;
  final Map<String, BudgetCategory> _categories = {};
  final Map<String, BudgetEntry> _entries = {};
  List<BudgetCategory> get categories => List.unmodifiable(_categories.values);
  List<BudgetEntry> get entries => List.unmodifiable(_entries.values);

  void saveCategory(BudgetCategory category) {
    if (category.id.trim().isEmpty || category.name.trim().isEmpty) {
      throw ArgumentError('La categoría necesita ID y nombre.');
    }
    final previous = _categories[category.id];
    if (previous != null &&
        previous.kind != category.kind &&
        _entries.values.any((entry) => entry.categoryId == category.id)) {
      throw StateError('Reasigna los movimientos antes de cambiar el tipo.');
    }
    _categories[category.id] = category;
  }

  void deleteCategory(String id) {
    if (_entries.values.any((entry) => entry.categoryId == id)) {
      throw StateError('La categoría tiene movimientos. Reasígnalos primero.');
    }
    _categories.remove(id);
  }

  void saveEntry(BudgetEntry entry) {
    _validatePeriod(entry.year, entry.month);
    if (entry.id.trim().isEmpty ||
        !_categories.containsKey(entry.categoryId) ||
        entry.amountCents <= 0 ||
        entry.amountCents > Money.maxCents) {
      throw ArgumentError('Movimiento, categoría o monto inválido.');
    }
    _entries[entry.id] = entry;
  }

  void deleteEntry(String id) => _entries.remove(id);

  BudgetSummary monthSummary(int year, int month) {
    _validatePeriod(year, month);
    return _summary(
      _entries.values.where((e) => e.year == year && e.month == month),
    );
  }

  BudgetSummary yearSummary(int year) {
    _validatePeriod(year, 1);
    return _summary(_entries.values.where((e) => e.year == year));
  }

  BudgetSummary _summary(Iterable<BudgetEntry> entries) {
    var income = 0;
    var expense = 0;
    for (final entry in entries) {
      if (_categories[entry.categoryId]!.kind == EntryKind.income) {
        income += entry.amountCents;
      } else {
        expense += entry.amountCents;
      }
    }
    return BudgetSummary(income, expense);
  }

  String exportYearCsv(int year) {
    _validatePeriod(year, 1);
    final rows = <List<String>>[
      [
        'año',
        'mes',
        'tipo',
        'categoría',
        'descripción',
        'ingresos_bob',
        'egresos_bob',
        'saldo_bob',
      ],
    ];
    for (var month = 1; month <= 12; month++) {
      final monthly =
          entries.where((e) => e.year == year && e.month == month).toList()
            ..sort((a, b) => a.id.compareTo(b.id));
      for (final entry in monthly) {
        final category = _categories[entry.categoryId]!;
        final income = category.kind == EntryKind.income;
        rows.add([
          '$year',
          '$month',
          income ? 'INGRESO' : 'EGRESO',
          category.name,
          entry.description,
          income ? _decimal(entry.amountCents) : '0.00',
          income ? '0.00' : _decimal(entry.amountCents),
          '',
        ]);
      }
      final summary = monthSummary(year, month);
      rows.add([
        '$year',
        '$month',
        'RESUMEN',
        '',
        '',
        _decimal(summary.income),
        _decimal(summary.expense),
        _decimal(summary.balance),
      ]);
    }
    final summary = yearSummary(year);
    rows.add([
      '$year',
      '',
      'TOTAL_ANUAL',
      '',
      '',
      _decimal(summary.income),
      _decimal(summary.expense),
      _decimal(summary.balance),
    ]);
    // Numeric cells are generated by the application, not user-controlled text.
    return '${rows.map((row) => row.asMap().entries.map((e) => e.key >= 5 ? e.value : csvCell(e.value)).join(',')).join('\r\n')}\r\n';
  }

  static void _validatePeriod(int year, int month) {
    if (year < 1 || year > 9999 || month < 1 || month > 12) {
      throw ArgumentError('Año o mes fuera de rango.');
    }
  }
}

String _decimal(int cents) =>
    '${cents < 0 ? '-' : ''}${cents.abs() ~/ 100}.${(cents.abs() % 100).toString().padLeft(2, '0')}';

/// RFC4180 quoting plus spreadsheet formula neutralization for untrusted text.
String csvCell(String input) {
  var value = input;
  if (RegExp(r'^[\s\x00-\x1f]*[=+\-@]').hasMatch(value) ||
      RegExp(r'^[\t\r\n]').hasMatch(value)) {
    value = "'$value";
  }
  if (value.contains(RegExp('[,"\r\n]'))) {
    value = '"${value.replaceAll('"', '""')}"';
  }
  return value;
}
